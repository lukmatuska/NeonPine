#!/usr/bin/env python3
"""Writes ../neonpine_test/anim_tables.h: lookup tables for the fixed-point animations (anim.c).

The CH32V003 has no FPU and no multiplier, so sin / exp / noise hashing come from tables.
Q12 = 4096 is 1.0. Rerun after changing anything here: python3 tools/gen_anim_tables.py
"""
import math
import os
import random

Q = 4096
out = os.path.join(os.path.dirname(__file__), "..", "neonpine_test", "anim_tables.h")

sin_tab = [round(Q * math.sin(2 * math.pi * k / 256)) for k in range(65)]           # quarter turn, 256 steps per turn
exp_tab = [round(Q * math.exp(-k / 16)) for k in range(129)]                       # e^-x, x = 0 .. 8 in 1/16
rng = random.Random(0x4E50)                                                        # fixed seed: same noise every build
perm = list(range(256))
rng.shuffle(perm)


def rows(vals, per=16):
    return "\n".join("\t" + ", ".join(str(v) for v in vals[i:i + per]) + "," for i in range(0, len(vals), per))


with open(out, "w") as f:
    f.write("// Generated by tools/gen_anim_tables.py - do not edit.\n#pragma once\n#include <stdint.h>\n\n")
    f.write("// sin(2 pi k / 256), Q12, first quarter (the rest by symmetry)\nstatic const uint16_t sin_tab[65] = {\n%s\n};\n\n" % rows(sin_tab))
    f.write("// exp(-k / 16), Q12 (x = 0 .. 8)\nstatic const uint16_t expneg_tab[129] = {\n%s\n};\n\n" % rows(exp_tab))
    f.write("// permutation of 0..255 for the value-noise hash\nstatic const uint8_t perm_tab[256] = {\n%s\n};\n" % rows(perm))
print("wrote", os.path.normpath(out))
