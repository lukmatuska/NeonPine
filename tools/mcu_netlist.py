#!/usr/bin/env python3
"""Write docs/mcu-netlist.md: the part of the netlist the firmware needs - every CH32V003 pin with its net, what it drives
(followed through series resistors), the 74HC595 chain bit order and the per-lamp driver table.
Generated from the schematic, so rerun it after any pin swap (gen.py / pinswap.py).
Usage: python3 tools/mcu_netlist.py"""
import os, re, subprocess, sys, tempfile
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
from sx import parse

PRJ = os.path.join(HERE, '..')
OUT = os.path.join(PRJ, 'docs', 'mcu-netlist.md')

# firmware notes per net (what the schematic cannot say: peripheral, remap, option bytes, polarity)
USE = {
    'USB_DM_MCU': 'USB D− (rv003usb `USB_PIN_DM 4`; EXTI4 falling edge, highest IRQ priority)',
    'USB_DP_MCU': 'USB D+ (rv003usb `USB_PIN_DP 2`)',
    'SR_LATCH': '74HC595 RCLK (U2, U3): rising edge copies the shift registers to the outputs',
    'SR_CLK': '74HC595 SRCLK (U2, U3), rising edge shifts; also test pad TP3',
    'SR_DATA': '74HC595 SER of U2. **PD7 = NRST pin: configure NRST as GPIO** (option byte RST_MODE, `minichlink -D`)',
    'GATE_DRV': 'Boost MOSFET gate (via R1 47R, R2 100k pull-down): **TIM2_CH3, AFIO TIM2_RM = 11** (full remap), ≈30 kHz, ≤60 % duty',
    'VFB': 'HV feedback, **ADC A4**: V_HV · 39k / 2.039M (105 V → 2.0 V), 10n filter',
    'LDR': 'Light sensor TEPT4400 (emitter, 22k to GND), **ADC A1**',
    'TOUCH2': 'Trunk touch pad TP2 via R11 1k, **ADC A0** (TKEY)',
    'SWIO': 'SWD programming / debug (pogo pads J2: 5V, SWIO, GND)',
    '+5V': 'VDD (USB 5 V after PTC + ferrite)', 'GND': 'VSS',
}
RAIL = {'GND': 'ground pours', '+5V': 'C6 100n at the pin; supply rail'}   # rails: not listed node by node
SR_OUT = ['QA', 'QB', 'QC', 'QD', 'QE', 'QF', 'QG', 'QH']

def lamp_role(net):
    m = re.fullmatch(r'LAMP(A?)(\d+)', net)
    if not m: return None
    n, a = int(m.group(2)), bool(m.group(1))
    side = 'A side: lamp pad 2' if a else 'K side: lamp pad 1'
    return n, a, f'LA{n} {side} switch (Q{10 + n} unit {"B" if a else "A"} via R{(50 if a else 40) + n} 22k); high = on = that electrode glows'

def main():
    with tempfile.TemporaryDirectory() as d:
        net_file = os.path.join(d, 'np.net')
        subprocess.run(['kicad-cli', 'sch', 'export', 'netlist', '--format', 'kicadsexpr', '-o', net_file,
                        os.path.join(PRJ, 'NeonPine.kicad_sch')], check=True, capture_output=True)
        t = parse(open(net_file).read())[0]
    g = lambda e, k: [x for x in e if isinstance(x, list) and x[0] == k]
    s = lambda e, k: g(e, k)[0][1].strip('"') if g(e, k) else ''
    value = {s(c, 'ref'): s(c, 'value') for c in g(t, 'components')[0][1:]}
    nets, pin_net, pin_fn = {}, {}, {}
    for n in g(t, 'nets')[0][1:]:
        name = s(n, 'name').lstrip('/')
        nodes = [(s(nd, 'ref'), s(nd, 'pin')) for nd in g(n, 'node')]
        nets[name] = nodes
        for nd in g(n, 'node'):
            pin_net[(s(nd, 'ref'), s(nd, 'pin'))] = name
            pin_fn[(s(nd, 'ref'), s(nd, 'pin'))] = re.sub(r'_\d+$', '', s(nd, 'pinfunction'))
    twopin = {r for r in value if re.fullmatch(r'[RCDL]\d+|FB\d+|F\d+', r)}

    def nodes_str(net, skip=()):
        out = []
        for ref, pin in nets[net]:
            if (ref, pin) in skip: continue
            out.append(f'{ref}.{pin}' + (f' ({value[ref]})' if ref in twopin else ''))
        return ', '.join(out)

    def path(net, start):
        """direct nodes; through a series resistor one hop further (not into the rails)"""
        parts = []
        for ref, pin in nets[net]:
            if (ref, pin) == start: continue
            if ref.startswith('R') and ref in twopin:
                other = pin_net.get((ref, '2' if pin == '1' else '1'))
                if other and other not in ('GND', '+5V'):
                    parts.append(f'{ref} {value[ref]} → **{other}**: ' + nodes_str(other, skip={(ref, '2' if pin == '1' else '1')}))
                    continue
            parts.append(f'{ref}.{pin}' + (f' ({value[ref]})' if ref in twopin else ''))
        return '; '.join(parts)

    L = ['# NeonPine – MCU netlist for firmware', '',
         '*Generated by `tools/mcu_netlist.py` from `NeonPine.kicad_sch` – do not edit by hand, rerun the script after pin changes.*', '',
         'MCU: **U1 CH32V003F4P6** (TSSOP-20), **VDD = 5 V**, HSI ×2 = 48 MHz (needed by rv003usb).', '',
         '## U1 pins', '', '| Pin | Port | Net | Firmware use | Connects to |', '|---|---|---|---|---|']
    for pin in sorted((p for (r, p) in pin_net if r == 'U1'), key=int):
        net = pin_net[('U1', pin)]
        lr = lamp_role(net)
        use = USE.get(net) or (lr[2] if lr else '')
        conn = path(net, ('U1', pin)) if net not in RAIL else RAIL[net]
        L.append(f'| {pin} | {pin_fn[("U1", pin)]} | {net} | {use} | {conn} |')

    # 74HC595 chain: SR_DATA -> U2 SER, U2 QH' -> U3 SER. Shift 16 bits MSB first, then pulse SR_LATCH.
    chain = [u for u in ('U2', 'U3')]
    assert pin_net[('U2', '14')] == 'SR_DATA' and pin_net[('U3', '14')] == 'SR_CHAIN' == pin_net[('U2', '9')]
    qpin = {}
    for u in chain:
        for p, fn in ((p, pin_fn[(r, p)]) for (r, p) in pin_net if r == u):
            if fn in SR_OUT: qpin[(u, fn)] = p
    L += ['', '## 74HC595 chain (U2 → U3)', '',
          '`SR_DATA` → U2 SER, U2 QH′ → U3 SER (`SR_CHAIN`); clock and latch are shared. /OE is tied low and /SRCLR high, so the outputs',
          'are random until the first latch (the boost is held off by R2 meanwhile). Shift a 16-bit word **MSB first**',
          '(`SR_DATA` valid before the `SR_CLK` rising edge), then pulse `SR_LATCH`. Word bit *b* ends up on:', '',
          '| Word bit | Output | Pin | Net | Drives |', '|---|---|---|---|---|']
    for bit in range(15, -1, -1):
        u = 'U3' if bit >= 8 else 'U2'
        q = SR_OUT[bit % 8]
        p = qpin[(u, q)]; net = pin_net[(u, p)]
        lr = lamp_role(net)
        drv = lr[2] if lr else ('– (not connected)' if net.startswith('unconnected') else path(net, (u, p)))
        L.append(f'| {bit} | {u} {q} | {p} | {net if not net.startswith("unconnected") else "–"} | {drv} |')

    # lamp table
    drv = {}
    for (r, p), net in pin_net.items():
        lr = lamp_role(net)
        if not lr or r not in ('U1', 'U2', 'U3'): continue
        if r == 'U1': where = f'U1 pin {p} = **{pin_fn[(r, p)]}**'
        else:
            q = pin_fn[(r, p)]; bit = SR_OUT.index(q) + (8 if r == 'U3' else 0)
            where = f'{r} {q} = **SR bit {bit}**'
        drv[(lr[0], lr[1])] = where
    L += ['', '## Lamps', '',
          'Each lamp sits in an H-bridge (DESIGN.md §2.3): turning the **K-side** switch on makes lamp pad 1 the cathode (that electrode glows),',
          'the **A-side** switch makes pad 2 the cathode. Never turn both on (dark, but both 150k pull-ups draw current).', '',
          '| Lamp | K side (net LAMPn) | A side (net LAMPAn) |', '|---|---|---|']
    for n in range(1, 11):
        L.append(f'| LA{n} | {drv.get((n, False), "?")} | {drv.get((n, True), "?")} |')

    L += ['', '## Peripheral / option-byte summary', '',
          '* **Option bytes:** NRST disabled (RST_MODE = GPIO) – PD7 carries SR_DATA. Keep it disabled if the rv003usb bootloader is',
          '  configured (its `configurebootloader` sets OB_RST_EN_DT1ms by default).',
          '* **AFIO:** TIM2_RM = 11 (TIM2_CH3 → PD6). The other TIM2 channels then map to PC1/PC7/PD5 – leave their outputs disabled.',
          '* **Timers:** TIM2 = boost PWM (CH3). TIM1 and SysTick are free (BAM frame, UI timing).',
          '* **ADC:** A0 = PA2 touch, A1 = PA1 light sensor, A4 = PD3 HV feedback (calibrate against Vrefint).',
          '* **USB (rv003usb `usb_config.h`):** `USB_PORT D`, `USB_PIN_DP 2`, `USB_PIN_DM 4`, no `USB_PIN_DPU` (R15 1k5 pulls D− to',
          '  VBUS permanently; force re-enumeration by driving D− low briefly). EXTI line 4 is taken; its handler must be the highest',
          '  priority and never be preempted – keep other ISRs short or preemptible.',
          '* **Reset state:** all pins are floating inputs. R2 holds the boost gate low, so HV+ stays at ≈ 5 V and the lamp switches',
          '  (floating bases, no pull-downs) cannot light anything; drive the lamp pins and latch the 595s before starting TIM2.',
          '']
    open(OUT, 'w').write('\n'.join(L))
    print('wrote', os.path.relpath(OUT, PRJ))

main()
