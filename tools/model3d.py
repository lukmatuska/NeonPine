"""Shared writer for the NeonPine 3D models (run from freecadcmd scripts).
save(name, parts) writes NeonPine.3dshapes/<name>.step (mm, for MCAD export) and
<name>.wrl (coloured VRML 2.0 in KiCad's 0.1" units, for the 3D viewer).
parts = [(label, Part.Shape, (r, g, b), transparency), ...]"""
import os
import Part, MeshPart

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'NeonPine.3dshapes')

def save(name, parts, script):
    os.makedirs(OUT, exist_ok=True)
    Part.makeCompound([p[1] for p in parts]).exportStep(os.path.join(OUT, name + '.step'))
    k = 1 / 2.54
    with open(os.path.join(OUT, name + '.wrl'), 'w') as f:
        f.write('#VRML V2.0 utf8\n# %s - generated by tools/%s\n' % (name, script))
        for label, shp, col, tr in parts:
            m = MeshPart.meshFromShape(Shape=shp, LinearDeflection=0.02, AngularDeflection=0.25, Relative=False)
            pts, facets = m.Topology
            f.write('Shape { # %s\n appearance Appearance { material Material { diffuseColor %.3f %.3f %.3f '
                    'specularColor 0.6 0.6 0.6 shininess 0.6 transparency %.2f } }\n' % (label, *col, tr))
            f.write(' geometry IndexedFaceSet { creaseAngle 0.5 coord Coordinate { point [\n')
            f.write(',\n'.join('%.5f %.5f %.5f' % (p.x * k, p.y * k, p.z * k) for p in pts))
            f.write(' ] }\n coordIndex [\n')
            f.write(',\n'.join('%d,%d,%d,-1' % t for t in facets))
            f.write(' ] } }\n')
    print('wrote', name, [(n, round(s.Volume, 2)) for n, s, *_ in parts])
